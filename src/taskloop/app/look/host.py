"""What the look stage reads and writes of the engine that runs it: one Protocol, so the stage has no hidden reach into the Engine."""
import threading
from collections.abc import Mapping, Sequence
from contextlib import AbstractContextManager
from pathlib import Path
from typing import Protocol

from tlkernel.artifact import ArtifactMeta
from tlkernel.asked import Asked
from tlkernel.beadsport import Beads
from tlkernel.checks import CheckRun
from tlkernel.config import VisualConfig
from tlkernel.plancheck import StageData
from tlkernel.stagefacts import LeftoverSink, Narrate, RepoKey
from tlkernel.wire import Open

from taskloop.adapters.looks import Methods


class OwnerItems(Protocol):
    """What the review stage left for the owner (the engine's `review`): the look stage files them in the owner-look bead."""
    unverified: list[Open]


class LookSteps(Protocol):
    def begin(self, step: str, text: str, **meta: object) -> int: ...
    def outcome(self, outcome: str, detail: str = ...) -> None: ...
    def move(self, to: str, cause: str, detail: str = ...) -> None: ...


class LookBudget(Protocol):
    @property
    def labels(self) -> list[str]: ...


class PictureBook(Protocol):
    """The look stage's own picture keeper (shots.Pictures), as the judge and the owner-look read it."""

    def visual_cfg(self) -> VisualConfig | None: ...
    def shots(self) -> list[str]: ...
    def stage_visual(self, st: StageData) -> bool: ...
    def shot_methods(self) -> Methods: ...
    def look_ready(self, st: StageData) -> bool: ...
    def show_pictures(self) -> list[tuple[str, ArtifactMeta]]: ...
    def before_pictures(self) -> list[tuple[Path, ArtifactMeta]]: ...
    def render_shots(self, reqs: Sequence[Open], rnd: int) -> tuple[list[str], list[str]]: ...
    def persist_look(self) -> None: ...


class CaseBook(Protocol):
    def cases_of(self, cls: str) -> list[str]: ...


class StageChecksView(Protocol):
    def stoppable(self, st: StageData, name: str, acceptance_first: bool = ..., groups: Sequence[str] | None = ...,
                  conflict_fix: Sequence[str] | None = ..., **meta: object) -> CheckRun: ...


class CheckoutPaths(Protocol):
    def changed_paths(self) -> list[str]: ...


class PendingKeeper(Protocol):
    def keep_pending(self, origin: str = ...) -> None: ...
    def keep_look(self) -> None: ...


class LockWaits(Protocol):
    def locked(self, what: str, path: Path | str, holder: str | None = ...) -> AbstractContextManager[Path | str]: ...


class RepoHolder(Protocol):
    @property
    def repo(self) -> RepoKey: ...


class LookPorts(Protocol):
    """What the look stage calls, as the engine's own handles (the run facts are `RunFacts`, the stage's own state `LookState`)."""

    @property
    def leftover_sink(self) -> LeftoverSink: ...

    @property
    def steps(self) -> LookSteps: ...
    @property
    def budget(self) -> LookBudget: ...
    @property
    def store(self) -> Beads: ...
    @property
    def pictures(self) -> PictureBook: ...
    @property
    def cases(self) -> CaseBook: ...
    @property
    def stage_checks(self) -> StageChecksView: ...
    @property
    def checkout(self) -> CheckoutPaths: ...
    @property
    def checkpoints(self) -> PendingKeeper: ...
    @property
    def waits(self) -> LockWaits: ...
    @property
    def log(self) -> Narrate: ...
    @property
    def ports(self) -> RepoHolder: ...

    def ai(self, node: str, title: str, prompt: str, *a: object, **kw: object) -> Asked: ...
    def comment(self, text: str) -> None: ...
    def warn(self, text: str) -> None: ...
    def now(self) -> float: ...
    def sh(self, cmd: Sequence[str], timeout: float = ..., check: bool = ..., save: Path | None = ..., env: Mapping[str, str] | None = ...,
           pin: bool = ..., what: str = ..., cwd: Path | None = ..., stop: threading.Event | None = ...) -> tuple[int, str]: ...


class LookHost(Protocol):
    """The hand-offs the look stage still shares with the engine: what bd said of the bead, the review's and the write's leftovers, the
    pause the judge asks for, and the two run facts that are not frozen (artifact_repo, render_stale). Deleted with RunFacts' last users."""

    @property
    def Blocked(self) -> type[Exception]: ...
    bead_parent: str
    bead_title: str
    at_stage: int
    last_flag: str
    @property
    def writer_family(self) -> str | None: ...
    retry_after: float
    leftovers: list[dict[str, str]]
    @property
    def review(self) -> OwnerItems: ...
    artifact_repo: str
    render_stale: bool
