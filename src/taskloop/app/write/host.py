"""The write stage's capabilities and the shared hand-offs its engine supplies."""
from collections.abc import Callable, Mapping, Sequence
from pathlib import Path
from typing import Protocol

from tlkernel.asked import Asked
from tlkernel.askspec import AskSpec
from tlkernel.beadsport import Beads
from tlkernel.checkpoint import Handoff as HandoffState
from tlkernel.checkpoint import StageProgress, WriterSession
from tlkernel.checks import CheckResult, CheckRun
from tlkernel.config import EngineConfig
from tlkernel.gitport import Git
from tlkernel.ids import BeadId, TreeSha
from tlkernel.paths import ConfigDir
from tlkernel.plancheck import PlanCheck, PlanData, StageData
from tlkernel.procport import Spawner
from tlkernel.stagefacts import LeftoverSink, Narrate, RepoKey, StepBook
from tlkernel.wire import Open

from taskloop.app.write.state import WriteState
from taskloop.domain.checks.writer_split import WriterSplit
from taskloop.domain.work.ledger import Ledger


class CaseBook(Protocol):
    def add_cases(self, new: list[Open]) -> None: ...
    def case_checks(self) -> list[PlanCheck]: ...
    def cases_text(self) -> str: ...
    def rules_text(self) -> str: ...
    def plan_text(self, stage: int | None = ...) -> str: ...
    def engine_unproven(self, unchecked: list[Open], checks: list[CheckResult]) -> list[Open]: ...
    def out_of_scope(self, items: list[Open]) -> list[Open]: ...


class FlakeBook(Protocol):
    def add_flakes(self, new: list[Open]) -> None: ...
    def flakes_text(self) -> str: ...
    def shared_text(self) -> str: ...


class Checkout(Protocol):
    def tree_hash(self) -> TreeSha: ...
    def base_sha(self) -> str: ...
    def task_diff(self) -> str: ...
    def slot_status(self) -> tuple[list[str], list[str], str]: ...


class Checkpoints(Protocol):
    def save(self, *, step: str = ..., stage: int = ..., rounds: int = ..., n: int = ..., feedback: str = ...,
             progress: StageProgress | None = ...) -> None: ...
    def keep_pending(self, origin: str = ...) -> None: ...


class Budget(Protocol):
    @property
    def labels(self) -> list[str]: ...


class CheckerPort(Protocol):
    def split(self) -> WriterSplit: ...


class StageChecks(Protocol):
    def stoppable(self, st: StageData, name: str, acceptance_first: bool = ..., groups: Sequence[str] | None = ...,
                  conflict_fix: Sequence[str] | None = ..., **meta: object) -> CheckRun: ...


class SavedRun(Protocol):
    def write(self, rec: CheckRun) -> None: ...


class WriteStores(Protocol):
    @property
    def check_run(self) -> Callable[[str, int | None], SavedRun]: ...


class Briefs(Protocol):
    def text(self) -> str: ...


class Routing(Protocol):
    def ledger(self) -> Ledger: ...


class Pictures(Protocol):
    def stage_visual(self, st: StageData) -> bool: ...
    def shot_methods(self) -> Mapping[str, object]: ...
    def mark_stale(self) -> None: ...
    def look_ready(self, st: StageData) -> bool: ...
    def shot_table(self) -> str: ...


class Judge(Protocol):
    def look_step(self, st: StageData, w: Open, name: str, last: bool = ..., *, family: str | None = ...) -> str: ...
    def look_write(self, st: StageData) -> str: ...
    def look_review(self, st: StageData, w: Open, fix: bool = ...) -> str: ...
    def look_judged(self, review: Open, st: StageData, w: Open, fix: bool) -> None: ...


class ReviewItems(Protocol):
    unchecked: list[Open]


class LookState(Protocol):
    @property
    def done(self) -> int: ...
    @done.setter
    def done(self, value: int) -> None: ...


class ReviewCap(Protocol):
    def review_cap(self, n: int) -> None: ...


class LinkCheck(Protocol):
    def link_judged(self, review: Open) -> None: ...


class Reload(Protocol):
    def safe_point(self, step: str) -> None: ...


class RepoHolder(Protocol):
    @property
    def repo(self) -> RepoKey: ...


class BriefingHost(Protocol):
    @property
    def checker(self) -> CheckerPort: ...
    @property
    def branch(self) -> str: ...
    @property
    def wt(self) -> str: ...


class PreparePorts(Protocol):
    @property
    def cfg(self) -> EngineConfig: ...
    @property
    def wt(self) -> str: ...
    @property
    def git(self) -> Git: ...
    @property
    def home(self) -> ConfigDir: ...
    @property
    def run_id(self) -> str: ...
    @property
    def spawner(self) -> Spawner: ...
    @property
    def bead_env(self) -> Mapping[str, str]: ...
    @property
    def log(self) -> Narrate: ...
    def blocked_for(self, why: str, kind: str) -> Exception: ...


class NewFilesHost(Protocol):
    @property
    def cfg(self) -> EngineConfig: ...
    @property
    def accepted_new(self) -> list[str]: ...
    @property
    def plan_data(self) -> PlanData | None: ...
    @property
    def wt(self) -> str: ...
    @property
    def checkout(self) -> Checkout: ...
    @property
    def evidence_dir(self) -> Path: ...
    @property
    def write(self) -> WriteState: ...
    @property
    def log(self) -> Narrate: ...
    @property
    def stage_tree(self) -> str: ...
    def comment(self, text: str) -> None: ...


class HandoffHost(Protocol):
    @property
    def cfg(self) -> EngineConfig: ...
    @property
    def writer(self) -> WriterSession: ...
    @property
    def writer_family(self) -> str | None: ...
    @property
    def briefs(self) -> Briefs: ...
    @property
    def cases(self) -> CaseBook: ...
    @property
    def checkout(self) -> Checkout: ...
    @property
    def wt(self) -> str: ...
    @property
    def stage_tree(self) -> str: ...
    @property
    def write(self) -> WriteState: ...
    @property
    def done(self) -> list[str]: ...
    @property
    def brief_file(self) -> Path: ...
    @property
    def handoff(self) -> HandoffState: ...
    @property
    def log(self) -> Narrate: ...
    @property
    def home(self) -> ConfigDir: ...
    @property
    def run_id(self) -> str: ...
    @property
    def routing(self) -> Routing: ...
    @property
    def filed(self) -> list[str]: ...


class Briefing(Protocol):
    def where(self, node: str, checks: Sequence[str] = ..., failed: Sequence[str] | None = ..., listed: Sequence[str] = ...) -> str: ...
    def base_red_text(self, run: CheckRun) -> str: ...
    def stage_checks_text(self, checks: Sequence[str], skip: Sequence[str] | None = ...) -> str: ...


class Handoff(Protocol):
    def drop_big(self, boundary: bool = ...) -> str: ...
    def accepted_text(self) -> str: ...
    def so_far_text(self) -> str: ...
    def delta(self, n: int, goal: str, files: str, anchors: str, checks: str, where: str, feedback: str, tail: str) -> str | None: ...
    def rounds_text(self, last: int = ..., each: int = ..., cap: int = ...) -> str: ...
    def seen_lows_text(self) -> str: ...
    def note_round(self, name: str, rnd: int, kind: str, writer: str = ..., open_items: Sequence[str] = ...) -> None: ...
    def note_lows(self, findings: Sequence[Open]) -> None: ...


class NewFiles(Protocol):
    def new_by_kind(self) -> dict[str, list[str]]: ...
    def stage_work(self, unexplained: list[str], ignored: list[str]) -> str: ...
    def new_files_brief(self, unexplained: list[str]) -> str: ...
    def undecided_new(self, unexplained: list[str], review: Open) -> list[str]: ...


class WritePorts(PreparePorts, Protocol):

    @property
    def leftover_sink(self) -> LeftoverSink: ...
    def blocked_for(self, why: str, kind: str, *, spec: AskSpec | None = ...) -> Exception: ...
    @property
    def steps(self) -> StepBook: ...
    @property
    def store(self) -> Beads: ...
    @property
    def cases(self) -> CaseBook: ...
    @property
    def shared(self) -> FlakeBook: ...
    @property
    def checkout(self) -> Checkout: ...
    @property
    def checkpoints(self) -> Checkpoints: ...
    @property
    def budget(self) -> Budget: ...
    @property
    def stage_checks(self) -> StageChecks: ...
    @property
    def stores(self) -> WriteStores: ...
    @property
    def briefs(self) -> Briefs: ...
    @property
    def briefing(self) -> Briefing: ...
    @property
    def routing(self) -> Routing: ...
    @property
    def pictures(self) -> Pictures: ...
    @property
    def judge(self) -> Judge: ...
    @property
    def hand(self) -> Handoff: ...
    @property
    def newfiles(self) -> NewFiles: ...
    @property
    def ask_flow(self) -> ReviewCap: ...
    @property
    def link_check(self) -> LinkCheck: ...
    @property
    def reload(self) -> Reload: ...
    @property
    def ports(self) -> RepoHolder: ...

    def ai(self, node: str, title: str, prompt: str, *a: object, **kw: object) -> Asked: ...
    def warn(self, text: str) -> None: ...
    def comment(self, text: str) -> None: ...


class AmendFlag(Protocol):
    """The engine's `amend` (the plan stage's amendment context) as write reads it: whether work precedes the plan's first stage."""

    amended: bool


class WriteHost(WritePorts, Protocol):
    """Shared run position, state and hand-offs; write-owned memory stays in WriteState."""

    bead: BeadId
    at_stage: int
    stage_tree: str
    amend: AmendFlag
    stuck_why: str
    last_run: CheckRun | None
    accepted_new: list[str]
    writer_family: str | None
    render_stale: bool
    artifact_repo: str
    run_dir: Path
    leftovers: list[dict[str, str]]
    stats: dict[str, int]
    plan_data: PlanData | None
    scope: str
    last_flag: str
    sessions: list[Open]
    evidence_dir: Path
    brief_file: Path
    @property
    def writer(self) -> WriterSession: ...
    @property
    def write(self) -> WriteState: ...
    @property
    def review(self) -> ReviewItems: ...
    @property
    def look(self) -> LookState: ...
