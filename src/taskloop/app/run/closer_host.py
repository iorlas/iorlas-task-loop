"""What the Closer reads of the engine that is closing: one small Protocol per part it calls, and CloserHost for the engine itself.
A test hands the Closer a small fake that has just these members; the type checker shows what a close needs."""
import threading
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Protocol

from taskloop.app.run.steps import Open
from taskloop.contracts import fence
from taskloop.contracts.checkpoint import Checkpoint, EndRec, Notes
from taskloop.contracts.config import EngineConfig
from taskloop.contracts.enums import Outcome
from taskloop.contracts.ids import BeadId
from taskloop.contracts.kinds import Kind
from taskloop.contracts.ports import Beads, Clock
from taskloop.domain import outcome as oc
from taskloop.domain.asks.spec import AskSpec
from taskloop.stores.bundle import Stores
from taskloop.stores.runlog import RunLog


class CloseSteps(Protocol):
    @property
    def cur(self) -> Open | None: ...
    @property
    def last(self) -> Open | None: ...
    @property
    def moved_from(self) -> int | None: ...
    @property
    def moved_to(self) -> str | None: ...
    def move(self, to: str, cause: str, detail: str = ...) -> None: ...
    def begin(self, step: str, text: str, **meta: object) -> int: ...
    def outcome(self, outcome: str, detail: str = ...) -> None: ...
    def end(self, outcome: str = ...) -> None: ...


class CloseCheckpoints(Protocol):
    def applied(self) -> frozenset[str]: ...
    def mark_applied(self, key: str) -> None: ...
    def close(self, why: str = ...) -> None: ...
    def keep_end(self, end: EndRec) -> None: ...
    def keep_notes(self, notes: Notes) -> None: ...
    def notes(self) -> Notes | None: ...
    def drop_unless_fenced(self) -> None: ...
    def keep_filed(self, lost: list[dict[str, str]] | None = ...) -> None: ...


class CloseTree(Protocol):
    def wip(self, why: str, everything: bool = ...) -> bool: ...
    def leave_slot(self, outcome: str, branch: str) -> None: ...


class CloseRecords(Protocol):
    def log_run(self) -> None: ...
    def file_trace(self, outcome: Outcome, why: str, sha: str) -> None: ...


class CloseReflector(Protocol):
    def reflect_run(self, outcome: str, why: str) -> Mapping[str, object] | None: ...


class CloseAskFlow(Protocol):
    def raise_ask(self, spec: AskSpec, why: str, kind: Kind) -> object: ...


class CloseOwnerLook(Protocol):
    def unverified_text(self) -> str: ...
    def file_owner_look(self) -> None: ...


class CloseJudge(Protocol):
    def is_look(self, u: Mapping[str, str]) -> bool: ...


class ClosePictures(Protocol):
    def keep_evidence(self) -> list[Path]: ...


class CloserHost(Protocol):
    """The engine, as the close reads it. It also satisfies FollowUpHost (app/land/followups.py), which the close hands it to."""

    disp: oc.Disposition | None
    kind: Kind
    fp: str
    storm: str
    asked: bool
    reflection: Mapping[str, object] | None
    dead: Checkpoint | None  # the checkpoint of a run that died inside its close (its outcome kept, a key unapplied), else None

    @property
    def bead(self) -> BeadId: ...
    @property
    def store(self) -> Beads: ...
    @property
    def log(self) -> RunLog: ...
    @property
    def stats(self) -> dict[str, int]: ...
    @property
    def leftovers(self) -> list[Mapping[str, str]]: ...
    @property
    def filed(self) -> list[str]: ...
    @property
    def cfg(self) -> EngineConfig: ...
    @property
    def wt(self) -> str | Path: ...
    @property
    def dry(self) -> bool: ...
    @property
    def clock(self) -> Clock: ...
    @property
    def claim(self) -> fence.Claim: ...
    @property
    def stores(self) -> Stores: ...
    @property
    def log_path(self) -> Path: ...
    @property
    def steps(self) -> CloseSteps: ...
    @property
    def checkpoints(self) -> CloseCheckpoints: ...
    @property
    def tree(self) -> CloseTree: ...
    @property
    def records(self) -> CloseRecords: ...
    @property
    def reflector(self) -> CloseReflector: ...
    @property
    def ask_flow(self) -> CloseAskFlow: ...
    @property
    def owner_look(self) -> CloseOwnerLook: ...
    @property
    def judge(self) -> CloseJudge: ...
    @property
    def pictures(self) -> ClosePictures: ...
    @property
    def cost(self) -> float: ...
    @property
    def t0(self) -> float: ...
    @property
    def branch(self) -> str: ...
    @property
    def plan_summary(self) -> str: ...
    @property
    def unverified(self) -> Sequence[object]: ...
    @property
    def unchecked(self) -> Sequence[Mapping[str, str]]: ...
    @property
    def verified(self) -> Sequence[Mapping[str, str]]: ...
    def sh(self, cmd: Sequence[str], timeout: float = ..., check: bool = ..., save: Path | None = ..., env: Mapping[str, str] | None = ...,
           pin: bool = ..., what: str = ..., cwd: Path | None = ...) -> tuple[int, str]: ...
    def detail(self, lines: list[str]) -> None: ...
    def git(self, *args: str) -> str: ...
    def comment(self, text: str) -> None: ...
    def warn(self, text: str) -> None: ...

    @property
    def halt(self) -> threading.Event: ...
