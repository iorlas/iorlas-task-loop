"""What the reset and probe steps need of a slot, so they sit below the pool that owns the slots."""
from typing import Protocol

from taskloop.app.slots.env import SlotEnv
from taskloop.contracts.bead import Bead
from taskloop.contracts.ids import BeadId
from taskloop.contracts.slots import Hold


class SlotNames(Protocol):
    def name_of(self, wt: str) -> str: ...


class SlotView(Protocol):
    @property
    def pool(self) -> SlotNames: ...
    @property
    def name(self) -> str: ...
    @property
    def env(self) -> SlotEnv: ...
    @property
    def dir(self) -> str: ...

    def slot_bead(self) -> Bead: ...
    def hold(self) -> Hold | None: ...
    def free_reason(self) -> str: ...
    def ready_for(self, bead: str, *, force: bool = False) -> None: ...
    def take_locked(self, why: str, bead: str = "", ticket: int | None = None) -> BeadId: ...
    def release_locked(self, bead: str | None, mine: bool, force: bool, gen: int | None = None) -> bool: ...
